function renderRematchSchedule() {
    const tableBody = document.getElementById("rematchScheduleBody");
    if (!tableBody) return;

    const days = ["月曜日", "火曜日", "水曜日", "木曜日", "金曜日", "土曜日", "日曜日"];

    const periods = [
        { key: "朝", label: "朝" },
        { key: "昼", label: "昼" },
        { key: "夜", label: "夜" }
    ];

    const scheduled = trainers.filter(trainer =>
        trainer.category === "gym" &&
        trainer.round === "rematch" &&
        trainer.callDay && trainer.callTime
    );

    tableBody.innerHTML = days.map((day, dayIndex) => {
        const cells = periods.map(period => {
            const matches = scheduled.filter(trainer =>
                trainer.callDay === day && trainer.callTime.startsWith(period.key)
            );

            if (!matches.length) return '<td class="schedule-empty">—</td>';

            return `<td>${matches.map(trainer =>
                `<a class="schedule-trainer" href="#${escapeHTML(trainer.id)}" data-trainer-id="${escapeHTML(trainer.id)}">${escapeHTML(trainer.name)}</a>`
            ).join("")}</td>`;
        }).join("");

        return `<tr data-day="${dayIndex}"><th scope="row">${day}</th>${cells}</tr>`;
    }).join("");

    const currentDay = (new Date().getDay() + 6) % 7;
    const todayRow = tableBody.querySelector(`tr[data-day="${currentDay}"]`);

    if (todayRow) todayRow.classList.add("schedule-today");

    tableBody.addEventListener("click", event => {
        const link = event.target.closest("[data-trainer-id]");
        if (!link) return;

        event.preventDefault();

        // 絞り込みでカードが非表示になっている場合も移動できるようにする
        searchInput.value = "";
        battleFilter.value = "all";
        categoryFilter.value = "all";
        renderTrainers();

        const card = document.getElementById(link.dataset.trainerId);

        if (card instanceof HTMLDetailsElement) {
            card.open = true;

            requestAnimationFrame(() => requestAnimationFrame(() => {
                card.scrollIntoView({ behavior: "smooth", block: "start" });
            }));
        }
    });
}

function renderTrainers() {
    const query = searchInput.value.trim().toLowerCase();
    const round = battleFilter.value;
    const category = categoryFilter.value;

    const filtered = trainers.filter(trainer => {
        const matchesRound =
            round === "all" || trainer.round === round;

        const matchesCategory =
            category === "all" || trainer.category === category;

        const matchesQuery =
            searchableText(trainer).includes(query);

        return matchesRound && matchesCategory && matchesQuery;
    });

    for (const categoryName of Object.keys(sectionLists)) {
        const sectionTrainers = filtered.filter(
            trainer => trainer.category === categoryName
        );

        sectionLists[categoryName].innerHTML = sectionTrainers.length
            ? sectionTrainers.map(renderTrainer).join("")
            : `<p class="empty-message">該当するトレーナーはいません。</p>`;

        sectionElements[categoryName].hidden =
            sectionTrainers.length === 0;
    }

    resultCount.textContent = `${filtered.length}件のトレーナー情報`;
}

searchInput.addEventListener("input", renderTrainers);
battleFilter.addEventListener("change", renderTrainers);
categoryFilter.addEventListener("change", renderTrainers);

resetFilters.addEventListener("click", () => {
    searchInput.value = "";
    battleFilter.value = "all";
    categoryFilter.value = "all";
    renderTrainers();
});

renderTrainers();
renderRematchSchedule();

/* =========================================================
   トレーナーを一度に1人だけ展開できるようにする
   ========================================================= */

document.addEventListener("toggle", event => {
    const openedTrainer = event.target;

    // トレーナーカード以外のdetailsは対象外
    if (
        !(openedTrainer instanceof HTMLDetailsElement) ||
        !openedTrainer.classList.contains("trainer-card") ||
        !openedTrainer.open
    ) {
        return;
    }

    // ほかに開いているカードを閉じる
    document.querySelectorAll("details[open]").forEach((details) => {
        if (details !== openedTrainer) {
            details.open = false;
        }
    });

    // レイアウト更新後に、開いたカードを画面上部へ移動
    requestAnimationFrame(() => {
        requestAnimationFrame(() => {
            openedTrainer.scrollIntoView({
                behavior: "smooth",
                block: "start"
            });
        });
    });
}, true);
