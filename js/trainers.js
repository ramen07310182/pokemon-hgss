function escapeHTML(value) {
    return String(value ?? "").replace(/[&<>"']/g, char => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
    })[char]);
}

function pokemonSprite(id) {
    return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${id}.png`;
}

function renderPokemon(pokemon) {
    const moves = Array.isArray(pokemon.moves) ? pokemon.moves : [];

    const moveHTML = moves.length
        ? `<ul class="move-list">${moves.map(move =>
            `<li>${escapeHTML(move)}</li>`
        ).join("")}</ul>`
        : `<p class="move-unknown">技構成は未確認です。参考資料を確認してください。</p>`;

    const typeClassMap = {
        "ノーマル": "normal",
        "ほのお": "fire",
        "みず": "water",
        "くさ": "grass",
        "でんき": "electric",
        "こおり": "ice",
        "かくとう": "fighting",
        "どく": "poison",
        "じめん": "ground",
        "ひこう": "flying",
        "エスパー": "psychic",
        "むし": "bug",
        "いわ": "rock",
        "ゴースト": "ghost",
        "ドラゴン": "dragon",
        "あく": "dark",
        "はがね": "steel",
        "フェアリー": "fairy"
    };

    const types = Array.isArray(pokemon.types) ? pokemon.types : [];

    const primaryType = types.length
        ? (typeClassMap[types[0]] || "unknown")
        : "unknown";

    const typeHTML = types.length
        ? types.map(type => {
            const typeClass = typeClassMap[type] || "unknown";
            return `<span class="type-badge type-${typeClass}">${escapeHTML(type)}</span>`;
        }).join("")
        : `<span class="type-badge type-unknown">未登録</span>`;

    const itemHTML = pokemon.item
        ? `<p class="pokemon-detail"><strong>持ち物：</strong>${escapeHTML(pokemon.item)}</p>`
        : "";

    return `
        <article class="pokemon-card pokemon-type-${primaryType}">
            <div class="pokemon-heading">
                <img
                    src="${pokemonSprite(pokemon.id)}"
                    alt="${escapeHTML(pokemon.name)}"
                    loading="lazy"
                    width="76"
                    height="76"
                    onerror="this.style.display='none'"
                >
                <div>
                    <p class="pokemon-name">${escapeHTML(pokemon.name)}</p>
                    <span class="pokemon-number">No. ${String(pokemon.id).padStart(3, "0")}</span>
                    <span class="pokemon-level">Lv. ${escapeHTML(pokemon.level)}</span>
                </div>
            </div>
            <div class="pokemon-types">
                <strong>タイプ：</strong>
                <div class="type-badge-list">${typeHTML}</div>
            </div>
            ${itemHTML}
            <p class="move-title">使用技</p>
            ${moveHTML}
        </article>
    `;
}

function renderTrainer(trainer) {
    const teamHTML = trainer.team && trainer.team.length
        ? trainer.team.map(renderPokemon).join("")
        : `<p class="empty-message">このトレーナーの手持ちデータは未登録です。</p>`;

    const rematchInfo = trainer.round === "rematch"
        ? `
            <section class="trainer-condition">
                <h4>再戦条件</h4>
                <p>${escapeHTML(trainer.condition || "電話番号登録後、指定日時に電話してください。")}</p>
                ${trainer.callDay ? `<p><strong>電話する曜日：</strong>${escapeHTML(trainer.callDay)}</p>` : ""}
                ${trainer.callTime ? `<p><strong>電話する時間：</strong>${escapeHTML(trainer.callTime)}</p>` : ""}
                <p><strong>再戦場所：</strong>${escapeHTML(trainer.location)}</p>
            </section>
        `
        : "";

    const sourceHTML = trainer.source
        ? `<a href="${escapeHTML(trainer.source)}" target="_blank" rel="noopener noreferrer">参考攻略情報</a>`
        : "参考リンク未登録";

    return `
        <details class="trainer-card" id="${escapeHTML(trainer.id)}">
            <summary>
                <span class="trainer-name">${escapeHTML(trainer.name)}</span>
                <span class="trainer-meta">
                    <span class="pill">${escapeHTML(trainer.categoryLabel)}</span>
                    <span class="pill round-pill round-${escapeHTML(trainer.round)}">${escapeHTML(
        trainer.round === "normal"
            ? "通常戦・初回"
            : trainer.round === "rematch"
                ? (trainer.category === "elite" ? "再戦・強化版" : "再戦・強化版")
                : "殿堂入り後"
    )}</span>
                </span>
            </summary>
            <div class="trainer-body">
                <p class="trainer-description">
                    <strong>場所：</strong>${escapeHTML(trainer.location)}<br>
                    <strong>得意タイプ：</strong>${escapeHTML(trainer.specialty)}
                </p>
                ${rematchInfo}
                <h4>手持ちポケモン</h4>
                <div class="team-list">${teamHTML}</div>
                <p class="strategy"><strong>攻略ポイント：</strong>${escapeHTML(trainer.strategy || "タイプ相性を確認しましょう。")}</p>
                <p class="source-note">${sourceHTML}</p>
            </div>
        </details>
    `;
}

function searchableText(trainer) {
    const pokemonText = (trainer.team || []).map(pokemon => [
        pokemon.name,
        ...(pokemon.moves || []),
        ...(pokemon.types || [])
    ].join(" ")).join(" ");

    return [
        trainer.name,
        trainer.categoryLabel,
        trainer.roundLabel,
        trainer.location,
        trainer.specialty,
        trainer.strategy,
        trainer.condition,
        trainer.callDay,
        trainer.callTime,
        pokemonText
    ].join(" ").toLowerCase();
}

